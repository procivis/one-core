use one_core::model::credential::CredentialStateEnum;
use one_core::model::identifier::IdentifierType;
use one_core::repository::DataRepository;
use rstest::rstest;
use sql_data_provider::DataLayer;

use crate::fixtures::{TestingCredentialParams, TestingIdentifierParams};
use crate::utils::context::TestContext;
use crate::utils::db_clients::credential_schemas::TestingCreateSchemaParams;
use crate::utils::db_clients::keys::ecdsa_testing_params;

#[rstest]
#[tokio::test]
async fn test_binding_cleanup_preserves_credential_references(
    #[values(false, true)] deleted: bool,
) {
    let (context, organisation, _, issuer, _) = TestContext::new_with_did(None).await;
    let key = context
        .db
        .keys
        .create(&organisation, ecdsa_testing_params())
        .await;
    let holder = context
        .db
        .identifiers
        .create(
            &organisation,
            TestingIdentifierParams {
                r#type: Some(IdentifierType::Key),
                key: Some(key),
                autogenerated: Some(true),
                ..Default::default()
            },
        )
        .await;
    let layer = DataLayer::build(context.db.db_conn.clone(), vec![]);
    let repository = layer.get_identifier_repository();
    assert!(
        !repository
            .has_credential_references(&issuer.id)
            .await
            .unwrap()
    );
    assert!(
        !repository
            .has_credential_references(&holder.id)
            .await
            .unwrap()
    );

    let schema = context
        .db
        .credential_schemas
        .create(
            "cleanup references",
            &organisation,
            TestingCreateSchemaParams::default(),
        )
        .await;
    context
        .db
        .credentials
        .create(
            &schema,
            CredentialStateEnum::Error,
            &issuer,
            "OPENID4VCI_FINAL1",
            TestingCredentialParams {
                holder_identifier: Some(holder.clone()),
                deleted_at: deleted.then(one_core::clock::now_utc),
                ..Default::default()
            },
        )
        .await;

    assert!(
        repository
            .has_credential_references(&issuer.id)
            .await
            .unwrap()
    );
    assert!(
        repository
            .has_credential_references(&holder.id)
            .await
            .unwrap()
    );
    assert!(
        !repository
            .has_credential_references(&uuid::Uuid::new_v4().into())
            .await
            .unwrap()
    );
}
