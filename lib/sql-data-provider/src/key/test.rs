struct TestSetup {
    pub db: sea_orm::DatabaseConnection,
    pub key_id: KeyId,
    pub organisation: Organisation,
}

async fn setup() -> TestSetup {
    setup_with_autogenerated(false).await
}

async fn setup_with_autogenerated(autogenerated: bool) -> TestSetup {
    let data_layer = setup_test_data_layer_and_connection().await;
    let db = data_layer.db;

    let organisation_id = insert_organisation_to_database(&db, None).await.unwrap();

    let now = one_core::clock::now_utc();
    let organisation = dummy_organisation(Some(organisation_id));

    let key_id = Uuid::new_v4().into();
    key::ActiveModel {
        id: Set(key_id),
        created_date: Set(now),
        last_modified: Set(now),
        name: Set("test".to_string()),
        public_key: Set(vec![]),
        key_reference: Set(None),
        storage_type: Set("test".to_string()),
        key_type: Set("test".to_string()),
        autogenerated: Set(autogenerated),
        organisation_id: Set(organisation_id),
        deleted_at: NotSet,
    }
    .insert(&db)
    .await
    .unwrap();

    TestSetup {
        db,
        key_id,
        organisation,
    }
}

struct TestListSetup {
    pub db: sea_orm::DatabaseConnection,
    pub organisation: Organisation,
    pub ids: Vec<KeyId>,
}

/// The first id in `ids` is a plain key (not autogenerated); the second is autogenerated.
async fn setup_list() -> TestListSetup {
    let TestSetup {
        db,
        key_id,
        organisation,
    } = setup().await;

    let now = one_core::clock::now_utc();
    let key2_id = Uuid::new_v4().into();
    key::ActiveModel {
        id: Set(key2_id),
        created_date: Set(now),
        last_modified: Set(now),
        name: Set("test2".to_string()),
        public_key: Set(vec![]),
        key_reference: Set(None),
        storage_type: Set("test2".to_string()),
        key_type: Set("test2".to_string()),
        autogenerated: Set(true),
        organisation_id: Set(organisation.id),
        deleted_at: NotSet,
    }
    .insert(&db)
    .await
    .unwrap();

    TestListSetup {
        db,
        organisation,
        ids: vec![key_id, key2_id],
    }
}

#[tokio::test]
async fn test_create_key_success() {
    let organisation_repository = MockOrganisationRepository::default();

    let TestSetup {
        db, organisation, ..
    } = setup().await;

    let provider = KeyProvider {
        db: TransactionManagerImpl::new(db.clone()),
        organisation_repository: Arc::new(organisation_repository),
    };

    let now = one_core::clock::now_utc();

    let id = Uuid::new_v4().into();
    let result = provider
        .create_key(Key {
            autogenerated: false,
            id,
            created_date: now,
            last_modified: now,
            public_key: vec![],
            name: "name".to_string(),
            key_reference: None,
            storage_type: "INTERNAL".to_string(),
            key_type: "RSA_4096".to_string(),
            organisation: organisation.into(),
        })
        .await;

    assert!(result.is_ok());
    assert_eq!(id, result.unwrap());
}

