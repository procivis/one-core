#[tokio::test]
async fn test_get_key_list_success() {
    let organisation_repository = MockOrganisationRepository::default();

    let TestListSetup {
        db,
        organisation,
        ids,
    } = setup_list().await;

    let provider = KeyProvider {
        db: TransactionManagerImpl::new(db.clone()),
        organisation_repository: Arc::new(organisation_repository),
    };

    let query = KeyListQuery {
        pagination: Some(ListPagination {
            page: 0,
            page_size: 5,
        }),
        sorting: None,
        filtering: Some(KeyFilterValue::OrganisationId(organisation.id).condition()),
        include: None,
    };

    let result = provider.get_key_list(query).await;
    assert!(result.is_ok());

    let data = result.unwrap();
    assert_eq!(data.total_pages, 1);
    assert_eq!(data.total_items, 2);
    assert_eq!(data.values.len(), 2);

    assert!(data.values.iter().all(|key| ids.contains(&key.id)));
}

#[tokio::test]
async fn test_get_key_list_and_filter_by_autogenerated() {
    let organisation_repository = MockOrganisationRepository::default();

    let TestListSetup {
        db,
        organisation,
        ids,
    } = setup_list().await;
    let (plain_id, autogenerated_id) = (ids[0], ids[1]);

    let provider = KeyProvider {
        db: TransactionManagerImpl::new(db.clone()),
        organisation_repository: Arc::new(organisation_repository),
    };

    // Unfiltered list reports the correct flag per row.
    let all = provider
        .get_key_list(KeyListQuery {
            pagination: None,
            sorting: None,
            filtering: Some(KeyFilterValue::OrganisationId(organisation.id).condition()),
            include: None,
        })
        .await
        .unwrap();
    assert_eq!(2, all.values.len());
    let autogenerated_key = all
        .values
        .iter()
        .find(|key| key.id == autogenerated_id)
        .unwrap();
    assert!(autogenerated_key.autogenerated);
    let plain_key = all.values.iter().find(|key| key.id == plain_id).unwrap();
    assert!(!plain_key.autogenerated);

    // Filtering by autogenerated = true returns only the autogenerated key.
    let autogenerated_only = provider
        .get_key_list(KeyListQuery {
            pagination: None,
            sorting: None,
            filtering: Some(
                KeyFilterValue::OrganisationId(organisation.id).condition()
                    & KeyFilterValue::Autogenerated(true).condition(),
            ),
            include: None,
        })
        .await
        .unwrap();
    assert_eq!(1, autogenerated_only.values.len());
    assert_eq!(autogenerated_id, autogenerated_only.values[0].id);

    // Filtering by autogenerated = false returns only the plain key.
    let not_autogenerated = provider
        .get_key_list(KeyListQuery {
            pagination: None,
            sorting: None,
            filtering: Some(
                KeyFilterValue::OrganisationId(organisation.id).condition()
                    & KeyFilterValue::Autogenerated(false).condition(),
            ),
            include: None,
        })
        .await
        .unwrap();
    assert_eq!(1, not_autogenerated.values.len());
    assert_eq!(plain_id, not_autogenerated.values[0].id);
}
