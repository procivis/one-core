    async fn up_sane(&self, manager: &SchemaManager<'_>) -> Result<(), DbErr> {
        manager
            .alter_table(
                Table::alter()
                    .table(Key::Table)
                    .add_column(boolean_null(Col::Autogenerated))
                    .to_owned(),
            )
            .await?;

        manager
            .get_connection()
            .execute_unprepared(&backfill_sql(manager.supported_db_type()))
            .await?;

        manager
            .alter_table(
                Table::alter()
                    .table(Key::Table)
                    .modify_column(boolean(Col::Autogenerated))
                    .to_owned(),
            )
            .await
    }

