const INDEX_UNIQUE_IDENTIFIER_NAME_ORGANISATION_DELETED_AT: &str =
    "index_Identifier_Name-OrganisationId-DeletedAt_Unique";

// Identifiers created automatically by the core (holder batch credential binding keys) are named
// with this prefix. did:webvh update keys are also autogenerated, but as of this migration they
// are never wrapped in their own `identifier` row (they only exist in `key`/`key_did`), so the
// UPDATE_KEY branch below currently matches nothing in practice. It is kept defensively for a
// KEY-type identifier that references such a key via `identifier.key_id`, should a future code
// path start creating one.
const BACKFILL_SQL: &str = r#"
UPDATE identifier
SET autogenerated = (
    name LIKE 'autogenerated-%'
    OR EXISTS (
        SELECT 1 FROM key_did
        WHERE key_did.key_id = identifier.key_id
          AND key_did.role = 'UPDATE_KEY'
    )
)
"#;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        disable_foreign_key_checks(manager).await?;
        if manager.supported_db_type() == SupportedDbType::Sqlite {
            self.up_sqlite(manager).await?;
        } else {
            self.up_sane(manager).await?;
        }
        enable_foreign_key_checks(manager).await?;

        Ok(())
    }
}

