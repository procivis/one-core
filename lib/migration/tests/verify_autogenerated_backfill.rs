#![allow(clippy::unwrap_used)]
#![allow(clippy::print_stdout)]

use migration::Migrator;
use sea_orm::{
    ConnectionTrait, Database, DatabaseBackend, DatabaseConnection, Statement, TransactionTrait,
};
use sea_orm_migration::MigratorTrait;

async fn setup(url: &str) -> DatabaseConnection {
    let db = Database::connect(url).await.unwrap();
    // Pin every statement to one physical connection: MySQL's FOREIGN_KEY_CHECKS toggle used by
    // the migrations is session-scoped, so it must stick across all the statements below (this
    // mirrors how `migration::runner::run_migrations` pins a transaction for the same reason).
    let txn = db.begin().await.unwrap();
    let total = Migrator::migrations()
        .iter()
        .take_while(|m| m.name() != "m20260831_090000_add_autogenerated_to_identifier")
        .count() as u32;
    Migrator::up(&txn, Some(total)).await.unwrap();

    let backend = txn.get_database_backend();
    // `key` is a reserved word in MySQL/MariaDB, so it needs backtick-quoting there; Postgres and
    // SQLite both accept the unquoted form fine.
    let key_table = if backend == DatabaseBackend::MySql {
        "`key`"
    } else {
        "key"
    };
    let exec = |sql: String| Statement::from_string(backend, sql);

    txn.execute(exec(
        "INSERT INTO organisation (id, created_date, last_modified) VALUES ('00000000-0000-0000-0000-000000000001', '2024-01-01 00:00:00', '2024-01-01 00:00:00')".to_string(),
    ))
    .await
    .unwrap();

    // Key used only as an update key (did:webvh) -> referenced via key_did with role UPDATE_KEY.
    txn.execute(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000010', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-webvh-did-00000000-0000-0000-0000-000000000020', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    // Key wrapped directly by a KEY-type identifier, also used as an UPDATE_KEY.
    txn.execute(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000011', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'wrapped-update-key', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    // Ordinary, non-autogenerated key wrapped by a KEY-type identifier.
    txn.execute(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000012', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-normal-key', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    txn.execute(exec(
        "INSERT INTO did (id, did, created_date, last_modified, name, type, method, organisation_id, deactivated) VALUES \
        ('00000000-0000-0000-0000-000000000020', 'did:webvh:example', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-webvh-did', 'LOCAL', 'WEBVH', '00000000-0000-0000-0000-000000000001', false)".to_string(),
    )).await.unwrap();

    txn.execute(exec(
        "INSERT INTO key_did (did_id, key_id, role, reference) VALUES ('00000000-0000-0000-0000-000000000020', '00000000-0000-0000-0000-000000000010', 'UPDATE_KEY', '#update-key-1')".to_string(),
    )).await.unwrap();
    txn.execute(exec(
        "INSERT INTO key_did (did_id, key_id, role, reference) VALUES ('00000000-0000-0000-0000-000000000020', '00000000-0000-0000-0000-000000000011', 'UPDATE_KEY', '#update-key-2')".to_string(),
    )).await.unwrap();

    // Case 1: DID-type identifier for the did:webvh DID itself -> must stay visible (not autogenerated).
    txn.execute(exec(
        "INSERT INTO identifier (id, created_date, last_modified, name, type, is_remote, state, organisation_id, did_id, key_id) VALUES \
        ('00000000-0000-0000-0000-000000000030', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-webvh-did', 'DID', false, 'ACTIVE', '00000000-0000-0000-0000-000000000001', '00000000-0000-0000-0000-000000000020', NULL)".to_string(),
    )).await.unwrap();

    // Case 2: name-pattern autogenerated identifier (holder batch credential binding key).
    txn.execute(exec(
        "INSERT INTO identifier (id, created_date, last_modified, name, type, is_remote, state, organisation_id, did_id, key_id) VALUES \
        ('00000000-0000-0000-0000-000000000031', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'autogenerated-key-00000000-0000-0000-0000-000000000012', 'KEY', false, 'ACTIVE', '00000000-0000-0000-0000-000000000001', NULL, '00000000-0000-0000-0000-000000000012')".to_string(),
    )).await.unwrap();

    // Case 3: KEY-type identifier wrapping a key that also carries the UPDATE_KEY role.
    txn.execute(exec(
        "INSERT INTO identifier (id, created_date, last_modified, name, type, is_remote, state, organisation_id, did_id, key_id) VALUES \
        ('00000000-0000-0000-0000-000000000032', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'wrapped-update-key', 'KEY', false, 'ACTIVE', '00000000-0000-0000-0000-000000000001', NULL, '00000000-0000-0000-0000-000000000011')".to_string(),
    )).await.unwrap();

    // Case 4: ordinary, user-named KEY-type identifier -> must stay visible.
    txn.execute(exec(
        "INSERT INTO identifier (id, created_date, last_modified, name, type, is_remote, state, organisation_id, did_id, key_id) VALUES \
        ('00000000-0000-0000-0000-000000000033', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-normal-key', 'KEY', false, 'ACTIVE', '00000000-0000-0000-0000-000000000001', NULL, '00000000-0000-0000-0000-000000000012')".to_string(),
    )).await.unwrap();

    Migrator::up(&txn, Some(1)).await.unwrap();
    txn.commit().await.unwrap();

    db
}

async fn assert_flags(db: &DatabaseConnection) {
    let backend = db.get_database_backend();
    let rows = db
        .query_all(Statement::from_string(
            backend,
            "SELECT id, autogenerated FROM identifier ORDER BY id".to_string(),
        ))
        .await
        .unwrap();

    let mut actual = Vec::new();
    for row in rows {
        let id: String = row.try_get("", "id").unwrap();
        let autogenerated: bool = row.try_get("", "autogenerated").unwrap();
        actual.push((id, autogenerated));
    }

    let expected = vec![
        (
            "00000000-0000-0000-0000-000000000030".to_string(),
            false, // the did:webvh identifier itself stays visible
        ),
        (
            "00000000-0000-0000-0000-000000000031".to_string(),
            true, // name LIKE 'autogenerated-%'
        ),
        (
            "00000000-0000-0000-0000-000000000032".to_string(),
            true, // key_id -> key_did.role = UPDATE_KEY
        ),
        (
            "00000000-0000-0000-0000-000000000033".to_string(),
            false, // ordinary key identifier stays visible
        ),
    ];

    similar_asserts::assert_eq!(actual, expected);
}

#[tokio::test]
async fn test_autogenerated_backfill_sqlite() {
    let db = setup("sqlite::memory:").await;
    assert_flags(&db).await;
}

#[tokio::test]
async fn test_autogenerated_backfill_mysql() {
    let Ok(base_url) = std::env::var("TEST_MYSQL_URL") else {
        println!("skipping: set TEST_MYSQL_URL to run against MariaDB/MySQL");
        return;
    };
    let mut url: url::Url = base_url.parse().unwrap();
    url.set_path("");
    let admin = Database::connect(url.to_owned()).await.unwrap();
    let db_name = format!("autogen_test_{}", ulid::Ulid::new());
    admin
        .execute_unprepared(&format!("CREATE DATABASE {db_name};"))
        .await
        .unwrap();
    url.set_path(&db_name);

    let db = setup(url.as_str()).await;
    assert_flags(&db).await;
}

