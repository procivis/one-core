#![allow(clippy::unwrap_used)]
#![allow(clippy::print_stdout)]

use migration::Migrator;
use sea_orm::{
    ConnectionTrait, Database, DatabaseBackend, DatabaseConnection, Statement, TransactionTrait,
};
use sea_orm_migration::MigratorTrait;

async fn setup(url: &str) -> DatabaseConnection {
    let db = Database::connect(url).await.unwrap();
    let txn = db.begin().await.unwrap();
    let total = Migrator::migrations()
        .iter()
        .take_while(|m| m.name() != "m20260902_090000_add_autogenerated_to_key")
        .count() as u32;
    Migrator::up(&txn, Some(total)).await.unwrap();

    let backend = txn.get_database_backend();
    let key_table = if backend == DatabaseBackend::MySql {
        "`key`"
    } else {
        "key"
    };
    let exec = |sql: String| Statement::from_string(backend, sql);

    txn.execute_raw(exec(
        "INSERT INTO organisation (id, created_date, last_modified) VALUES ('00000000-0000-0000-0000-000000000001', '2024-01-01 00:00:00', '2024-01-01 00:00:00')".to_string(),
    ))
    .await
    .unwrap();

    // did:webvh update key, referenced via key_did with role UPDATE_KEY. Its name doesn't match
    // the legacy "autogenerated-" pattern, so only the UPDATE_KEY join can catch it.
    txn.execute_raw(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000010', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-webvh-did-00000000-0000-0000-0000-000000000020', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    // Legacy-named autogenerated holder-binding key, from before the switch to bare-uuid naming.
    txn.execute_raw(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000011', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'autogenerated-00000000-0000-0000-0000-000000000011', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    // Ordinary key: neither name-matched nor an UPDATE_KEY -> must stay visible.
    txn.execute_raw(exec(format!(
        "INSERT INTO {key_table} (id, created_date, last_modified, name, public_key, key_reference, storage_type, key_type, organisation_id) VALUES \
        ('00000000-0000-0000-0000-000000000012', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-normal-key', 'x', 'x', 'INTERNAL', 'EDDSA', '00000000-0000-0000-0000-000000000001')"
    ))).await.unwrap();

    txn.execute_raw(exec(
        "INSERT INTO did (id, did, created_date, last_modified, name, type, method, organisation_id, deactivated) VALUES \
        ('00000000-0000-0000-0000-000000000020', 'did:webvh:example', '2024-01-01 00:00:00', '2024-01-01 00:00:00', 'my-webvh-did', 'LOCAL', 'WEBVH', '00000000-0000-0000-0000-000000000001', false)".to_string(),
    )).await.unwrap();

    txn.execute_raw(exec(
        "INSERT INTO key_did (did_id, key_id, role, reference) VALUES ('00000000-0000-0000-0000-000000000020', '00000000-0000-0000-0000-000000000010', 'UPDATE_KEY', '#update-key-1')".to_string(),
    )).await.unwrap();

    Migrator::up(&txn, Some(1)).await.unwrap();
    txn.commit().await.unwrap();

    db
}

async fn assert_flags(db: &DatabaseConnection) {
    let backend = db.get_database_backend();
    let key_table = if backend == DatabaseBackend::MySql {
        "`key`"
    } else {
        "key"
    };
    let rows = db
        .query_all_raw(Statement::from_string(
            backend,
            format!("SELECT id, autogenerated FROM {key_table} ORDER BY id"),
        ))
        .await
        .unwrap();

    let mut actual = Vec::new();
    for row in rows {
        let id: String = row.try_get("", "id").unwrap();
        let autogenerated: bool = row.try_get("", "autogenerated").unwrap();
        actual.push((id, autogenerated));
    }

    let expected = vec![
        (
            "00000000-0000-0000-0000-000000000010".to_string(),
            true, // key_did.role = UPDATE_KEY
        ),
        (
            "00000000-0000-0000-0000-000000000011".to_string(),
            true, // name LIKE 'autogenerated-%'
        ),
        (
            "00000000-0000-0000-0000-000000000012".to_string(),
            false, // ordinary key stays visible
        ),
    ];

    similar_asserts::assert_eq!(actual, expected);
}

#[tokio::test]
async fn test_autogenerated_key_backfill_sqlite() {
    let db = setup("sqlite::memory:").await;
    assert_flags(&db).await;
}

#[tokio::test]
async fn test_autogenerated_key_backfill_mysql() {
    let Ok(base_url) = std::env::var("TEST_MYSQL_URL") else {
        println!("skipping: set TEST_MYSQL_URL to run against MariaDB/MySQL");
        return;
    };
    let mut url: url::Url = base_url.parse().unwrap();
    url.set_path("");
    let admin = Database::connect(url.to_owned()).await.unwrap();
    let db_name = format!("autogen_key_test_{}", ulid::Ulid::new());
    admin
        .execute_unprepared(&format!("CREATE DATABASE {db_name};"))
        .await
        .unwrap();
    url.set_path(&db_name);

    let db = setup(url.as_str()).await;
    assert_flags(&db).await;
}

