    pub(super) async fn create_local_did_identifier(
        &self,
        request: CreateDidRequestDTO,
        params: CreateLocalIdentifierRequestParams,
    ) -> Result<Identifier, Error> {
        let now = params.now;
        let organisation = Related::new(
            params.organisation_id,
            self.organisation_repository.to_owned(),
        );

        let did = self
            .create_did_without_identifier(request, organisation.clone(), now)
            .await?;
        let logo_id = if let Some(logo) = params.logo {
            Some(self.persist_identifier_logo(logo.0, now).await?)
        } else {
            None
        };

        let id = Uuid::new_v4().into();
        let identifier = Identifier {
            id,
            created_date: now,
            last_modified: now,
            name: params.name.clone(),
            organisation,
            data: IdentifierData::Did(did.into()),
            is_remote: false,
            state: IdentifierState::Active,
            deleted_at: None,
            trust_information: Default::default(),
            autogenerated: params.autogenerated,
            logo: logo_id,
            translations: self
                .parse_translations(id, &params.name, params.translations, params.now)
                .into(),
        };
        self.identifier_repository
            .create(identifier.to_owned())
            .await
            .map_err(map_already_exists_error)?;

        Ok(identifier)
    }

