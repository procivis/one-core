    pub(super) async fn create_local_certificate_identifier(
        &self,
        requests: Vec<CreateCertificateRequestDTO>,
        params: CreateLocalIdentifierRequestParams,
    ) -> Result<Identifier, Error> {
        let id = Uuid::new_v4().into();
        let organisation = Related::new(
            params.organisation_id,
            self.organisation_repository.to_owned(),
        );

        let mut certificates: Vec<Certificate> = vec![];
        for request in requests {
            let cert = self
                .validate_and_prepare_certificate(id, organisation.clone(), request)
                .await?;
            validate_no_conflicts(&certificates, &cert)?;
            certificates.push(cert);
        }
        let now = params.now;
        let logo_id = if let Some(logo) = params.logo {
            Some(self.persist_identifier_logo(logo.0, now).await?)
        } else {
            None
        };
        let identifier = Identifier {
            id,
            created_date: params.now,
            last_modified: params.now,
            name: params.name.clone(),
            organisation,
            data: IdentifierData::Certificate(RelatedVec::from(certificates.clone())),
            is_remote: false,
            state: IdentifierState::Active,
            deleted_at: None,
            trust_information: Default::default(),
            autogenerated: params.autogenerated,
            logo: logo_id,
            translations: self
                .parse_translations(id, &params.name, params.translations, now)
                .into(),
        };
        self.identifier_repository
            .create(identifier.to_owned())
            .await
            .map_err(map_already_exists_error)?;

        for certificate in certificates {
            self.certificate_repository
                .create(certificate)
                .await
                .map_err(|err| match err {
                    DataLayerError::AlreadyExists(_) => Error::CertificateAlreadyExists,
                    e => e.error_while("creating certificate").into(),
                })?;
        }

        Ok(identifier)
    }

