use one_dto_mapper::{From, Into, convert_inner};
use serde::{Deserialize, Serialize};
use shared_types::{KeyId, OrganisationId};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::model::common::GetListResponse;
use crate::model::key::{ExactKeyFilterColumn, Key};

pub struct KeyRequestDTO {
    pub organisation_id: OrganisationId,
    pub key_type: String,
    pub key_params: serde_json::Value,
    pub name: String,
    pub storage_type: String,
    pub storage_params: serde_json::Value,
}

#[derive(Clone, Debug)]
pub struct KeyResponseDTO {
    pub id: Uuid,
    pub created_date: OffsetDateTime,
    pub last_modified: OffsetDateTime,
    pub organisation_id: OrganisationId,
    pub name: String,
    pub public_key: Vec<u8>,
    pub key_type: String,
    pub storage_type: String,
    pub is_remote: bool,
    pub autogenerated: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize, From)]
#[from(Key)]
pub struct KeyListItemResponseDTO {
    pub id: Uuid,
    #[serde(with = "time::serde::rfc3339")]
    pub created_date: OffsetDateTime,
    #[serde(with = "time::serde::rfc3339")]
    pub last_modified: OffsetDateTime,
    pub name: String,
    pub public_key: Vec<u8>,
    pub key_type: String,
    pub storage_type: String,
    #[from(rename = "key_reference", with_fn_ref = "Option::is_none")]
    pub is_remote: bool,
    pub autogenerated: bool,
}

pub type GetKeyListResponseDTO = GetListResponse<KeyListItemResponseDTO>;

#[derive(Clone, Debug)]
pub struct KeyFilterParamsDTO {
    pub name: Option<String>,
    pub key_types: Option<Vec<String>>,
    pub key_storages: Option<Vec<String>>,
    pub ids: Option<Vec<KeyId>>,
    pub exact: Option<Vec<ExactKeyFilterColumn>>,
    pub is_remote: Option<bool>,
    pub autogenerated: Option<bool>,
    pub organisation_id: OrganisationId,
    pub created_date_after: Option<OffsetDateTime>,
    pub created_date_before: Option<OffsetDateTime>,
    pub last_modified_after: Option<OffsetDateTime>,
    pub last_modified_before: Option<OffsetDateTime>,
}

#[derive(Debug, Clone, Into)]
#[into(crate::proto::csr_creator::GenerateCsrRequest)]
pub struct KeyGenerateCSRRequestDTO {
    pub profile: KeyGenerateCSRRequestProfile,
    pub subject: KeyGenerateCSRRequestSubjectDTO,
    #[into(with_fn = convert_inner)]
    pub subject_alternative_name: Option<KeyGenerateCSRRequestSubjectAlternativeNameDTO>,
}

#[derive(Debug, Clone, Into, PartialEq, Eq)]
#[into(crate::proto::csr_creator::CsrRequestProfile)]
pub enum KeyGenerateCSRRequestProfile {
    Generic,
    Mdl,
    Ca,
}

#[derive(Debug, Clone, Into)]
#[into(crate::proto::csr_creator::CsrRequestSubject)]
pub struct KeyGenerateCSRRequestSubjectDTO {
    pub country_name: Option<String>,
    pub common_name: Option<String>,

    pub state_or_province_name: Option<String>,
    pub organisation_name: Option<String>,
    pub locality_name: Option<String>,
    pub serial_number: Option<String>,
}

#[derive(Debug, Clone, Into)]
#[into(crate::proto::csr_creator::CsrRequestSubjectAlternativeName)]
pub struct KeyGenerateCSRRequestSubjectAlternativeNameDTO {
    pub dns_name: Vec<String>,
}

#[derive(Debug)]
pub struct KeyGenerateCSRResponseDTO {
    pub content: String,
}
