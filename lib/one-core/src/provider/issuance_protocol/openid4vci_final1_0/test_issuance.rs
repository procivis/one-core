async fn generic_mdoc_credential(state: CredentialStateEnum) -> Credential {
    generic_credential_with_format(state, "MDOC").await
}

async fn generic_credential_with_format(state: CredentialStateEnum, format: &str) -> Credential {
    let key = dummy_key();

    let credential_schema = CredentialSchema {
        formats: vec![CredentialSchemaFormat {
            id: Uuid::new_v4().into(),
            created_date: crate::clock::now_utc(),
            last_modified: crate::clock::now_utc(),
            credential_schema_id: Uuid::new_v4().into(),
            format: CredentialFormat::from(format),
            ecosystem_schema_id: "CredentialSchemaId".to_owned(),
            claim_mappings: Default::default(),
        }]
        .into(),
        allow_revocation: false,
        ..dummy_credential()
            .await
            .schema
            .as_ref()
            .await
            .unwrap()
            .to_owned()
    };
    let credential_schema = backfill_default_translations(credential_schema, "en")
        .await
        .unwrap();
    let credential_format = credential_schema
        .formats
        .as_ref()
        .await
        .unwrap()
        .first()
        .cloned();
    Credential {
        state,
        suspend_end_date: None,
        holder_identifier: Some(
            Identifier {
                data: IdentifierData::Did((dummy_did()).into()),
                ..dummy_identifier()
            }
            .into(),
        ),
        issuer_identifier: Some(
            Identifier {
                data: IdentifierData::Did(
                    (Did {
                        keys: vec![RelatedKey {
                            role: KeyRole::AssertionMethod,
                            key: key.to_owned(),
                            reference: "1".to_string(),
                        }]
                        .into(),
                        ..dummy_did()
                    })
                    .into(),
                ),
                ..dummy_identifier()
            }
            .into(),
        ),
        key: Some(key.into()),
        schema: credential_schema.into(),
        format: credential_format.map(Into::into),
        ..dummy_credential().await
    }
}

