fn mock_webvh_log_request(client: &mut MockHttpClient, url: String, response: Response) {
    let mut sender = MockHttpClient::new();
    sender
        .expect_send()
        .with(
            eq(url.clone()),
            always(),
            eq(Some(HashMap::from([(
                "Accept".to_string(),
                "text/jsonl".to_string(),
            )]))),
            eq(Method::Get),
            always(),
        )
        .return_once(move |_, _, _, _, _| Ok(response));
    client
        .expect_get()
        .with(eq(url))
        .return_once(move |url| RequestBuilder::new(Arc::new(sender), Method::Get, url));
}

fn key(id: Uuid, handle: &KeyHandle, key_type: KeyAlgorithmType) -> Key {
    let now = crate::clock::now_utc();
    Key {
        id: id.into(),
        created_date: now,
        last_modified: now,
        public_key: handle.public_key_as_raw(),
        name: id.to_string(),
        key_reference: None,
        storage_type: "INTERNAL".to_string(),
        key_type: key_type.to_string(),
        autogenerated: false,
        organisation: dummy_organisation(None).into(),
    }
}

fn did_key_document(handle: &KeyHandle) -> DidDocument {
    let multibase = handle.public_key_as_multibase().unwrap();
    let did: DidValue = format!("did:key:{multibase}").parse().unwrap();
    let vm = format!("{did}#{multibase}");
    DidDocument {
        context: json!(["https://www.w3.org/ns/did/v1"]),
        id: did.clone(),
        verification_method: vec![DidVerificationMethod {
            id: vm.clone(),
            r#type: "Multikey".to_string(),
            controller: did.to_string(),
            public_key_jwk: handle.public_key_as_jwk().unwrap(),
        }],
        authentication: Some(vec![vm.clone()]),
        assertion_method: Some(vec![vm]),
        key_agreement: None,
        capability_invocation: None,
        capability_delegation: None,
        also_known_as: None,
        service: None,
    }
}

