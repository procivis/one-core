#[tokio::test]
async fn rejects_bcs_issuer_log_with_invalid_pre_rotation_transition() {
    let log = include_str!("vectors/bcs-issuer.did.jsonl");
    let mut provider = MockDidMethodProvider::new();
    provider.expect_resolve().returning(|did| {
        let multibase = did.as_str().strip_prefix("did:key:").unwrap();
        Ok(did_key_document(&Eddsa.parse_multibase(multibase).unwrap()))
    });
    let mut setup = setup(MockHttpClient::new());
    setup.method.did_method_provider = Arc::new(provider);
    let first: Value = serde_json::from_str(log.lines().next().unwrap()).unwrap();
    let second: Value = serde_json::from_str(log.lines().nth(1).unwrap()).unwrap();

    for field in ["updateKeys", "nextKeyHashes"] {
        let mut altered = second.clone();
        altered["parameters"].as_object_mut().unwrap().remove(field);
        let hash = hash_entry(&altered, first["versionId"].as_str().unwrap()).unwrap();
        altered["versionId"] = json!(format!("2-{hash}"));
        let altered_log = format!("{}\n{}", first, altered);
        let error = setup
            .method
            .verify_log(&altered_log, None)
            .await
            .unwrap_err();
        assert!(
            error.to_string().contains(&format!("explicit {field}")),
            "{error}"
        );
    }

    let mut altered = second.clone();
    altered["parameters"]["updateKeys"] = first["parameters"]["updateKeys"].clone();
    let hash = hash_entry(&altered, first["versionId"].as_str().unwrap()).unwrap();
    altered["versionId"] = json!(format!("2-{hash}"));
    let error = setup
        .method
        .verify_log(&format!("{}\n{}", first, altered), None)
        .await
        .unwrap_err();
    assert!(error.to_string().contains("no prior commitment"), "{error}");

    let mut altered = second.clone();
    altered["proof"][0]["verificationMethod"] = first["proof"][0]["verificationMethod"].clone();
    let error = setup
        .method
        .verify_log(&format!("{}\n{}", first, altered), None)
        .await
        .unwrap_err();
    assert!(
        error.to_string().contains("not an active update key"),
        "{error}"
    );
}

